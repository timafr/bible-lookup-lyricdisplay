def clean(value: str | None) -> str:
    return re.sub(r"\s+", " ", value or "").strip()


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(f"Source file is missing: {SOURCE}")

    root = ET.parse(SOURCE).getroot()
    books = []
    total_verses = 0

    for book_element in root.findall("BIBLEBOOK"):
        name = clean(book_element.get("bname"))
        chapters = []
        for chapter_element in book_element.findall("CHAPTER"):
            verses = []
            for verse_element in chapter_element.findall("VERS"):
                text = clean("".join(verse_element.itertext()))
                if text:
                    verses.append(text)
            chapters.append(verses)
            total_verses += len(verses)
        books.append({
            "id": int(book_element.get("bnumber", "0")),
            "name": name,
            "aliases": ALIASES.get(name, [name.lower()]),
            "chapters": chapters,
        })

    payload = {
        "translation": "Синодальный перевод",
        "source": "seven1m/open-bibles, rus-synodal.zefania.xml",
        "license": "Public Domain",
        "books": books,
        "bookCount": len(books),
        "verseCount": total_verses,
    }
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"Created {TARGET}: {len(books)} books, {total_verses} verses")


if __name__ == "__main__":
    main()
